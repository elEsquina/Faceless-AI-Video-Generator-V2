"""Data schemas and transfer models for the MCP-driven AI Video Generation Pipeline."""

from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional


class VideoCategory(str, Enum):
    """Supported video content categories."""
    KIDS_ANIMATED_STORY = "kids_animated_story"
    GENERAL_EXPLANATORY = "general_explanatory"
    CS_MATH_EDUCATIONAL = "cs_math_educational"


class AspectRatio(str, Enum):
    """Video aspect ratios."""
    PORTRAIT_9_16 = "9:16"
    LANDSCAPE_16_9 = "16:9"
    SQUARE_1_1 = "1:1"


class AnimationEngine(str, Enum):
    """Supported animation engines."""
    BLENDER = "blender"
    THREE_JS_REMOTION = "three_js_remotion"
    MANIM = "manim"
    HYBRID = "hybrid"


class AudioType(str, Enum):
    """Types of audio elements."""
    VOICEOVER = "voiceover"
    SOUND_EFFECT = "sound_effect"
    BACKGROUND_MUSIC = "background_music"


class ValidationStatus(str, Enum):
    """Status outcomes from quality validation."""
    PASSED = "passed"
    WARNING = "warning"
    FAILED = "failed"


class JobState(str, Enum):
    """Lifecycle states of a generation job."""
    INITIALIZED = "initialized"
    PLAN_PENDING = "plan_pending"
    PLAN_VALIDATED = "plan_validated"
    EXECUTING = "executing"
    COMPLETED = "completed"
    FAILED = "failed"


@dataclass
class JobRequest:
    """User video generation request parameters stored in request.json."""
    video_type: VideoCategory
    topic_or_prompt: str
    target_duration_seconds: float
    language: str = "en"
    aspect_ratio: AspectRatio = AspectRatio.LANDSCAPE_16_9


@dataclass
class WordTimestamp:
    """Timestamp alignment for a single word in TTS output."""
    word: str
    start_time: float
    end_time: float


@dataclass
class CaptionStyle:
    """Stylistic configuration for animated captions."""
    font_name: str
    font_size: int
    primary_color: str
    highlight_color: str
    animation_preset: str


@dataclass
class CaptionCue:
    """Timed subtitle and text splash event on the shared timeline."""
    text: str
    start_time: float
    end_time: float
    style: Optional[CaptionStyle] = None


@dataclass
class AudioCue:
    """Audio cue definition for SFX or BGM mapped to the shared timeline."""
    cue_id: str
    audio_type: AudioType
    source_uri: Optional[Path] = None
    start_time: float = 0.0
    duration_seconds: float = 0.0
    volume_level: float = 1.0


@dataclass
class TimelineInterval:
    """A bounded segment within the shared video timeline."""
    track_name: str
    start_time: float
    end_time: float

    @property
    def duration_seconds(self) -> float:
        pass


@dataclass
class SharedTimeline:
    """One master timeline coordinating visuals, narration, captions, and sound."""
    total_duration_seconds: float
    visual_intervals: List[TimelineInterval] = field(default_factory=list)
    narration_intervals: List[TimelineInterval] = field(default_factory=list)
    caption_cues: List[CaptionCue] = field(default_factory=list)
    audio_cues: List[AudioCue] = field(default_factory=list)


@dataclass
class SceneSpec:
    """Per-scene specification generated by the external AI director in plan.json."""
    scene_id: str
    index: int
    engine: AnimationEngine
    start_time: float
    end_time: float
    narration_text: str
    visual_description: str
    code_file: Optional[str] = None
    inline_code: Optional[str] = None
    sound_effects: List[AudioCue] = field(default_factory=list)


@dataclass
class PlanManifest:
    """Complete structured plan.json generated by external AI director."""
    job_id: str
    title: str
    category: VideoCategory
    aspect_ratio: AspectRatio
    target_duration_seconds: float
    shared_timeline: SharedTimeline
    scenes: List[SceneSpec] = field(default_factory=list)
    background_music: List[AudioCue] = field(default_factory=list)


@dataclass
class SceneErrorReport:
    """Validation or execution errors localized to an individual scene."""
    scene_id: str
    stage: str
    error_message: str
    suggested_fix: Optional[str] = None


@dataclass
class JobErrorReport:
    """Consolidated errors in errors.json for inspection by the external AI agent."""
    job_id: str
    status: ValidationStatus
    global_errors: List[str] = field(default_factory=list)
    scene_errors: List[SceneErrorReport] = field(default_factory=list)


@dataclass
class JobStatusRecord:
    """Status record persisted in status.json."""
    job_id: str
    state: JobState
    progress_percentage: float = 0.0
    current_stage: Optional[str] = None
    output_video_path: Optional[Path] = None
    errors: List[str] = field(default_factory=list)


@dataclass
class RenderedSceneAsset:
    """Rendered visual output corresponding to a scene."""
    scene_id: str
    video_path: Path
    duration_seconds: float
    engine: AnimationEngine


@dataclass
class ValidationResult:
    """Validation report detailing pipeline checks and integrity."""
    status: ValidationStatus
    is_valid: bool
    issues: List[str] = field(default_factory=list)
    scenes_to_regenerate: List[str] = field(default_factory=list)


@dataclass
class FinalVideoResult:
    """Result metadata of the generated final MP4 video."""
    video_path: Path
    total_duration_seconds: float
    validation: ValidationResult
